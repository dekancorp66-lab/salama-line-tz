import { Injectable } from '@nestjs/common';
import { KnowledgeLoaderService } from './knowledge/knowledge-loader.service';
import { KnowledgeRetrievalService } from './knowledge/knowledge-retrieval.service';

type Language = 'sw' | 'en';

@Injectable()
export class AiService {
  constructor(
    private readonly loader: KnowledgeLoaderService,
    private readonly retrieval: KnowledgeRetrievalService,
  ) {}

  health() {
    const records = this.loader.count();
    return {
      status: records > 0 ? 'ok' : 'unavailable',
      service: 'SalamaLine AI',
      knowledgeBase: { loaded: records > 0, records },
    };
  }

  ask(question: string, requestedLanguage?: Language) {
    const language = requestedLanguage || this.detectLanguage(question);
    const safety = this.assessSafety(question);
    const results = this.retrieval.search(question, language, 4);

    if (safety.escalate) {
      return {
        answer: language === 'sw'
          ? 'Inaonekana suala hili linaweza kuhitaji msaada wa haraka wa mtu halisi. Ikiwa uko kwenye hatari ya sasa, tafuta sehemu salama ikiwa unaweza na wasiliana na huduma za dharura za eneo lako au mtu mzima unayemwamini. Unaweza pia kuomba kuunganishwa na mhudumu aliyefunzwa kupitia njia rasmi za SalamaLine. Si lazima utoe maelezo zaidi hapa.'
          : 'This may need timely support from a real person. If you are in immediate danger, move toward a safer place if you can and contact local emergency services or a trusted adult. You can also request connection to a trained responder through SalamaLine’s official channels. You do not need to share more details here.',
        language,
        sources: [],
        status: 'safety_guidance',
        safety,
        disclaimer: this.disclaimer(language),
      };
    }

    if (!results.length || results[0].score < 0.12) {
      return {
        answer: language === 'sw'
          ? 'Sina taarifa zilizothibitishwa za kutosha kujibu swali hili kwa uhakika. Sitaki kubuni taarifa. Tafadhali wasiliana na mtaalamu au mhudumu aliyethibitishwa katika eneo lako. Kifurushi hiki kinahusu Tanzania Bara pekee.'
          : 'I do not have enough verified information to answer this reliably, and I will not invent details. Please consult a qualified professional or verified local service. This package covers Mainland Tanzania only.',
        language,
        sources: [],
        status: 'no_reliable_answer',
        safety,
        disclaimer: this.disclaimer(language),
      };
    }

    const answer = results.map((item) => {
      const title = item.record.title || item.record.topic || item.record.id;
      return `${title}: ${item.text}`;
    }).join('\n\n');

    const sourceIds = [...new Set(results.flatMap((item) =>
      Array.isArray(item.record.source_ids) ? item.record.source_ids.filter((id): id is string => typeof id === 'string') : [],
    ))];

    return {
      answer,
      language,
      sources: sourceIds.map((id) => ({ id, name: this.sourceName(id) })),
      status: 'answered',
      safety,
      disclaimer: this.disclaimer(language),
      note: language === 'sw'
        ? 'Majibu haya yametokana na rekodi za maarifa zilizopakiwa; hayajazalishwa na LLM.'
        : 'This answer is retrieved from the loaded knowledge records; it was not generated by an LLM.',
    };
  }

  private sourceName(id: string): string {
    const names: Record<string, string> = {
      WHO_TRAINING_2021: 'WHO, Caring for Women Subjected to Violence: Training Curriculum (2021)',
      TZA_LCA_2023: 'The Law of the Child Act, Cap. 13, Revised Edition 2023 (Mainland Tanzania)',
      WHO_CLINICAL_HANDBOOK_2014: 'WHO, Health Care for Women Subjected to IPV or Sexual Violence: Clinical Handbook (2014)',
      TZA_NPA_VAWC_II_2024_2029: 'Tanzania National Plan of Action to End Violence Against Women and Children II (2024/25–2028/29)',
    };
    return names[id] || id;
  }

  private detectLanguage(question: string): Language {
    const swWords = /\b(nina|nini|vipi|je|msaada|mtoto|ukatili|sheria|nawezaje|tafadhali|wapi|yangu|kwangu)\b/i;
    return swWords.test(question) ? 'sw' : 'en';
  }

  private assessSafety(question: string) {
    const text = question.toLocaleLowerCase();
    const urgentPatterns = [
      /\b(niko|upo|yuko)\s+(kwenye\s+)?hatari\b/,
      /\b(anani|wanani)?tishia\b/,
      /\b(amenipiga|ananipiga|anapiga)\b/,
      /\b(i am|someone is|they are)\s+(in\s+)?immediate danger\b/,
      /\b(being|is)\s+(hurt|attacked|threatened)\b/,
      /\bsexual assault happening now\b/,
    ];
    const escalate = urgentPatterns.some((pattern) => pattern.test(text));
    return {
      escalate,
      reason: escalate ? 'possible_immediate_safety_risk' : 'standard',
      humanSupportRecommended: escalate,
    };
  }

  private disclaimer(language: Language): string {
    return language === 'sw'
      ? 'SalamaLine AI si huduma ya dharura, si mtaalamu wa afya au sheria, na haiwezi kuwasiliana na huduma za dharura kwa niaba yako.'
      : 'SalamaLine AI is not an emergency service or a health/legal professional, and it cannot contact emergency services on your behalf.';
  }
}
